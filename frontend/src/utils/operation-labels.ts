export function operationValue(value: unknown): string {
  if (value === null || value === undefined) return '—'
  if (value === '') return '（空）'
  if (typeof value === 'boolean') return value ? '是' : '否'
  return typeof value === 'object' ? JSON.stringify(value, null, 2) : String(value)
}
