DROP TABLE IF EXISTS inventory_transaction;
DROP TABLE IF EXISTS inventory_locked_allocation;
DROP TABLE IF EXISTS inventory_balance;
DROP TABLE IF EXISTS sku;

CREATE TABLE sku (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku_code VARCHAR(80) NOT NULL,
    model VARCHAR(100),
    configuration VARCHAR(1000),
    product_version VARCHAR(80),
    color VARCHAR(80),
    lock_body VARCHAR(80),
    unit VARCHAR(20)
);
CREATE TABLE inventory_balance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warehouse_id BIGINT NOT NULL,
    sku_id BIGINT NOT NULL,
    actual_quantity INT NOT NULL,
    locked_quantity INT NOT NULL,
    in_transit_quantity INT NOT NULL,
    source_supplier_name VARCHAR(200),
    inventory_remark VARCHAR(500),
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version INT NOT NULL DEFAULT 0
);
CREATE TABLE inventory_locked_allocation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inventory_balance_id BIGINT NOT NULL,
    lock_source VARCHAR(30) NOT NULL,
    quantity INT NOT NULL
);
CREATE TABLE inventory_transaction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warehouse_id BIGINT NOT NULL,
    sku_id BIGINT NOT NULL,
    transaction_type VARCHAR(40) NOT NULL,
    business_type VARCHAR(40) NOT NULL,
    business_no VARCHAR(80) NOT NULL,
    actual_delta INT NOT NULL,
    locked_delta INT NOT NULL,
    transit_delta INT NOT NULL,
    actual_before INT NOT NULL,
    actual_after INT NOT NULL,
    locked_before INT NOT NULL,
    locked_after INT NOT NULL,
    transit_before INT NOT NULL,
    transit_after INT NOT NULL,
    operated_at TIMESTAMP NOT NULL
);

