package com.internalops.workbench;

import com.internalops.auth.CurrentUser;
import com.internalops.auth.UserRole;
import com.internalops.customerfund.CustomerFundService;
import org.junit.jupiter.api.*;
import org.springframework.context.annotation.*;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.embedded.*;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.setup.MockMvcBuilders;
import org.springframework.transaction.annotation.EnableTransactionManagement;
import org.springframework.transaction.PlatformTransactionManager;
import java.math.BigDecimal;
import java.util.concurrent.*;
import static org.assertj.core.api.Assertions.*;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.*;

class OrderPaymentApiTest {
    @Configuration @EnableTransactionManagement(proxyTargetClass=true)
    static class Config {
        @Bean EmbeddedDatabase database() { return new EmbeddedDatabaseBuilder().setType(EmbeddedDatabaseType.H2).setName("order-payment-"+System.nanoTime()).addScript("customer-fund-schema.sql").build(); }
        @Bean JdbcTemplate jdbc(EmbeddedDatabase db) { return new JdbcTemplate(db); }
        @Bean PlatformTransactionManager transactionManager(EmbeddedDatabase db) { return new DataSourceTransactionManager(db); }
        @Bean CustomerFundService funds(JdbcTemplate jdbc) { return new CustomerFundService(jdbc); }
        @Bean FinanceWorkflowService workflow(JdbcTemplate jdbc,CustomerFundService funds) { return new FinanceWorkflowService(jdbc,null,funds); }
    }
    AnnotationConfigApplicationContext context;JdbcTemplate jdbc;FinanceWorkflowService workflow;MockMvc mvc;
    @BeforeEach void setup() {
        context=new AnnotationConfigApplicationContext(Config.class);jdbc=context.getBean(JdbcTemplate.class);workflow=context.getBean(FinanceWorkflowService.class);
        jdbc.execute("ALTER TABLE sales_order ADD total_amount DECIMAL(19,4) DEFAULT 100");
        jdbc.execute("ALTER TABLE sales_order ADD receipt_confirmed_at TIMESTAMP");
        jdbc.execute("ALTER TABLE sales_order ADD version INT DEFAULT 0");
        jdbc.execute("ALTER TABLE customer_receipt ALTER COLUMN id BIGINT GENERATED BY DEFAULT AS IDENTITY");
        for (String column : new String[]{"payment_method VARCHAR(100)","payment_remark VARCHAR(500)","received_at TIMESTAMP","confirmed_by BIGINT","reviewed_by BIGINT","reviewed_at TIMESTAMP","review_remark VARCHAR(500)"}) jdbc.execute("ALTER TABLE customer_receipt ADD "+column);
        jdbc.execute("ALTER TABLE customer_receipt ALTER COLUMN id RESTART WITH 100");
        jdbc.update("UPDATE customer_fund_account SET balance=500 WHERE customer_id=1");
        CurrentUser.set(new CurrentUser(9,"finance","财务",UserRole.FINANCE));
        mvc=MockMvcBuilders.standaloneSetup(new FinanceController(workflow,null,null)).build();
    }
    @AfterEach void cleanup(){CurrentUser.clear();context.close();}
    @Test void paymentDebitsOnlyRemainingAmountAndAutomaticallySettlesFinance() throws Exception {
        mvc.perform(post("/api/finance/orders/10/pay").contentType("application/json").content("{\"expectedAmount\":80}"))
                .andExpect(status().isOk()).andExpect(jsonPath("$.data.paymentStatus").value("PAID"))
                .andExpect(jsonPath("$.data.customerBalance").value(420));
        assertThat(jdbc.queryForObject("SELECT SUM(COALESCE(confirmed_amount,amount)) FROM customer_receipt WHERE sales_order_id=10",BigDecimal.class)).isEqualByComparingTo("100");
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM customer_fund_ledger WHERE entry_type='ORDER_RECEIPT'",Integer.class)).isEqualTo(1);
        mvc.perform(post("/api/finance/orders/10/pay").contentType("application/json").content("{\"expectedAmount\":80}"))
                .andExpect(status().isConflict());
        assertThat(balance()).isEqualByComparingTo("420");
    }
    @Test void insufficientBalanceAndStaleAmountNeverChangeFundsOrReceipts() throws Exception {
        jdbc.update("UPDATE customer_fund_account SET balance=50");
        mvc.perform(post("/api/finance/orders/10/pay").contentType("application/json").content("{\"expectedAmount\":80}"))
                .andExpect(status().isBadRequest());
        assertThat(balance()).isEqualByComparingTo("50");
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM customer_fund_ledger",Integer.class)).isZero();
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM customer_receipt",Integer.class)).isEqualTo(1);
        mvc.perform(post("/api/finance/orders/10/pay").contentType("application/json").content("{\"expectedAmount\":100}"))
                .andExpect(status().isConflict());
    }
    @Test void draftCancelledPendingReviewAndOrdinaryUsersAreBlocked() throws Exception {
        for(String status:new String[]{"DRAFT","CANCELLED"}) {
            jdbc.update("UPDATE sales_order SET status=? WHERE id=10",status);
            assertThatThrownBy(()->workflow.payOrder(10,new BigDecimal("80"))).hasMessageContaining("不能支付");
        }
        jdbc.update("UPDATE sales_order SET status='SHIPPED' WHERE id=10");
        jdbc.update("INSERT INTO customer_receipt(sales_order_id,amount,review_status) VALUES(10,10,'PENDING')");
        assertThatThrownBy(()->workflow.payOrder(10,new BigDecimal("80"))).hasMessageContaining("待复核");
        CurrentUser.set(new CurrentUser(3,"sales","销售",UserRole.USER));
        mvc.perform(post("/api/finance/orders/10/pay").contentType("application/json").content("{\"expectedAmount\":80}"))
                .andExpect(status().isForbidden());
        assertThat(balance()).isEqualByComparingTo("500");
    }
    @Test void shippedOrdersCanPayAndConcurrentClicksDeductOnce() throws Exception {
        jdbc.update("UPDATE sales_order SET status='SHIPPED' WHERE id=10");
        ExecutorService executor=Executors.newFixedThreadPool(2);CountDownLatch start=new CountDownLatch(1);
        Callable<Boolean> pay=()->{CurrentUser.set(new CurrentUser(9,"finance","财务",UserRole.FINANCE));try{start.await();workflow.payOrder(10,new BigDecimal("80"));return true;}catch(IllegalStateException expected){return false;}finally{CurrentUser.clear();}};
        try { Future<Boolean> a=executor.submit(pay),b=executor.submit(pay);start.countDown();assertThat(java.util.List.of(a.get(10,TimeUnit.SECONDS),b.get(10,TimeUnit.SECONDS))).containsExactlyInAnyOrder(true,false); }
        finally {executor.shutdownNow();}
        assertThat(balance()).isEqualByComparingTo("420");
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM customer_fund_ledger",Integer.class)).isEqualTo(1);
    }
    @Test void partialPaymentsAccumulateAndRejectStaleRetries() throws Exception {
        mvc.perform(post("/api/finance/orders/10/pay").contentType("application/json").content("{\"expectedAmount\":80,\"amount\":30}"))
                .andExpect(status().isOk()).andExpect(jsonPath("$.data.paymentStatus").value("PARTIALLY_PAID"))
                .andExpect(jsonPath("$.data.receivedAmount").value(50)).andExpect(jsonPath("$.data.outstandingAmount").value(50));
        mvc.perform(post("/api/finance/orders/10/pay").contentType("application/json").content("{\"expectedAmount\":80,\"amount\":30}"))
                .andExpect(status().isConflict());
        assertThat(balance()).isEqualByComparingTo("470");
        mvc.perform(post("/api/finance/orders/10/pay").contentType("application/json").content("{\"expectedAmount\":50,\"amount\":50}"))
                .andExpect(status().isOk()).andExpect(jsonPath("$.data.paymentStatus").value("PAID"))
                .andExpect(jsonPath("$.data.receivedAmount").value(100)).andExpect(jsonPath("$.data.outstandingAmount").value(0));
        assertThat(balance()).isEqualByComparingTo("420");
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM customer_fund_ledger",Integer.class)).isEqualTo(2);
    }
    @Test void rejectsInvalidPartialAmountsAndAllowsAffordablePartialPayment() throws Exception {
        for (String amount : new String[]{"0","-1","81","0.00001"}) {
            mvc.perform(post("/api/finance/orders/10/pay").contentType("application/json")
                    .content("{\"expectedAmount\":80,\"amount\":"+amount+"}"))
                    .andExpect(status().isBadRequest());
        }
        assertThat(balance()).isEqualByComparingTo("500");
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM customer_fund_ledger",Integer.class)).isZero();
        jdbc.update("UPDATE customer_fund_account SET balance=30 WHERE customer_id=1");
        mvc.perform(post("/api/finance/orders/10/pay").contentType("application/json").content("{\"expectedAmount\":80,\"amount\":30}"))
                .andExpect(status().isOk()).andExpect(jsonPath("$.data.customerBalance").value(0));
    }
    private BigDecimal balance(){return jdbc.queryForObject("SELECT balance FROM customer_fund_account WHERE customer_id=1",BigDecimal.class);}
}
